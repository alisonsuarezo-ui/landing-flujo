-- Campuslands AI Academy · Reto 4
-- Esquema inicial: interesados (leads), seguimiento y usuarios administradores.
-- SQL estándar compatible con PostgreSQL 13+ (y H2 en modo PostgreSQL para pruebas).
-- ============================================================================

-- Interesados registrados desde la landing.
CREATE TABLE leads (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(120)             NOT NULL,
    correo              VARCHAR(160)             NOT NULL,
    telefono            VARCHAR(30),
    programa_interes    VARCHAR(20)              NOT NULL,
    estado              VARCHAR(20)              NOT NULL DEFAULT 'NUEVO',
    fecha_registro      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_leads_estado
        CHECK (estado IN ('NUEVO', 'CONTACTADO', 'INTERESADO', 'INSCRITO', 'DESCARTADO')),
    CONSTRAINT ck_leads_programa
        CHECK (programa_interes IN ('IGNITION', 'BOOSTER', 'LIFTOFF', 'ODYSSEY', 'NEBULA')),
    CONSTRAINT ck_leads_nombre_no_vacio CHECK (LENGTH(TRIM(nombre)) >= 2),
    -- Control de registros repetidos: un mismo correo no se inscribe dos veces al mismo programa.
    -- El correo se normaliza a minúsculas en el backend antes de guardar.
    CONSTRAINT uq_leads_correo_programa UNIQUE (correo, programa_interes)
);

CREATE INDEX ix_leads_estado ON leads (estado);
CREATE INDEX ix_leads_programa ON leads (programa_interes);
CREATE INDEX ix_leads_fecha_registro ON leads (fecha_registro);

-- Historial cronológico de cada interesado: cambios de estado y notas.
CREATE TABLE seguimiento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id         BIGINT                   NOT NULL,
    nota            VARCHAR(2000),
    estado_anterior VARCHAR(20),
    estado_nuevo    VARCHAR(20),
    fecha           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responsable     VARCHAR(160)             NOT NULL,

    CONSTRAINT fk_seguimiento_lead
        FOREIGN KEY (lead_id) REFERENCES leads (id) ON DELETE CASCADE,
    CONSTRAINT ck_seguimiento_estado_anterior
        CHECK (estado_anterior IS NULL OR estado_anterior IN ('NUEVO', 'CONTACTADO', 'INTERESADO', 'INSCRITO', 'DESCARTADO')),
    CONSTRAINT ck_seguimiento_estado_nuevo
        CHECK (estado_nuevo IS NULL OR estado_nuevo IN ('NUEVO', 'CONTACTADO', 'INTERESADO', 'INSCRITO', 'DESCARTADO')),
    -- Cada registro del historial debe aportar algo: una nota o un cambio de estado.
    CONSTRAINT ck_seguimiento_contenido CHECK (nota IS NOT NULL OR estado_nuevo IS NOT NULL)
);

CREATE INDEX ix_seguimiento_lead_fecha ON seguimiento (lead_id, fecha);

-- Usuarios del panel administrativo. La contraseña se guarda como hash BCrypt, nunca en texto plano.
CREATE TABLE usuarios_admin (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo         VARCHAR(160)             NOT NULL,
    nombre         VARCHAR(120)             NOT NULL,
    password_hash  VARCHAR(100)             NOT NULL,
    activo         BOOLEAN                  NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_usuarios_admin_correo UNIQUE (correo)
);
